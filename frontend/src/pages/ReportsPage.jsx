import React, { useState } from "react";
import { 
  FileText, Download, CheckCircle, Database, Layers, ShieldCheck, 
  Search, Filter, FolderArchive, ArrowDownToLine 
} from "lucide-react";
import { SATELLITE_SPECIFICATIONS } from "../data/placeholderData";
import downloadableFiles from "../data/downloadable_files.json";

export default function ReportsPage() {
  const [selectedCategory, setSelectedCategory] = useState("all");
  const [formatFilter, setFormatFilter] = useState("all");
  const [searchQuery, setSearchQuery] = useState("");

  const categories = ["all", "Random Forest", "U-Net", "Proximity Analysis", "Reports"];
  const formats = ["all", "CSV", "JSON", "GeoJSON", "TIF", "PNG"];

  const filteredFiles = downloadableFiles.filter((file) => {
    // category filter
    if (selectedCategory !== "all") {
      if (selectedCategory === "U-Net" && !file.category.includes("U-Net")) return false;
      if (selectedCategory === "Random Forest" && file.category !== "Random Forest") return false;
      if (selectedCategory === "Proximity Analysis" && file.category !== "Proximity Analysis") return false;
      if (selectedCategory === "Reports" && !file.category.includes("Reports")) return false;
    }
    // format filter
    if (formatFilter !== "all") {
      if (formatFilter === "GeoJSON" && file.ext !== "GEOJSON") return false;
      if (formatFilter === "CSV" && file.ext !== "CSV") return false;
      if (formatFilter === "JSON" && file.ext !== "JSON") return false;
      if (formatFilter === "TIF" && file.ext !== "TIF") return false;
      if (formatFilter === "PNG" && file.ext !== "PNG") return false;
    }
    // search filter
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      return file.name.toLowerCase().includes(q) || file.path.toLowerCase().includes(q);
    }
    return true;
  });

  const handleDownload = (file) => {
    alert(`File available in repository:\n${file.path}\nSize: ${file.size_kb} KB`);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="pb-2 border-b border-slate-200">
        <h2 className="text-xl font-bold text-slate-900 tracking-tight">Reports &amp; Verified Output Repository</h2>
        <p className="text-xs text-slate-500 mt-0.5">
          Verified catalog of all {downloadableFiles.length} actual analytical files generated by Random Forest, U-Net, and Proximity pipelines
        </p>
      </div>

      {/* Featured Primary Exports Cards */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-5">
        <div className="bg-white border border-slate-200 rounded-xl p-5 shadow-xs flex flex-col justify-between">
          <div>
            <div className="w-9 h-9 rounded-lg bg-teal-50 text-teal-600 flex items-center justify-center mb-3">
              <Database className="w-5 h-5" />
            </div>
            <h3 className="text-sm font-bold text-slate-900">RF Clean Proximity Summary</h3>
            <p className="text-xs text-slate-500 mt-1 leading-normal">
              Consolidated 2021–2026 tabular dataset with mean &amp; median distance metrics and perimeter exposures.
            </p>
            <div className="mt-2 text-[10px] font-mono text-slate-400">
              outputs/proximity_rf_clean_2021-2026/proximity_rf_clean_summary.csv
            </div>
          </div>
          <button
            onClick={() => alert("Path: outputs/proximity_rf_clean_2021-2026/proximity_rf_clean_summary.csv")}
            className="mt-4 w-full py-2 px-3 rounded-lg bg-slate-900 hover:bg-slate-800 text-white text-xs font-semibold flex items-center justify-center gap-2 transition-colors cursor-pointer"
          >
            <ArrowDownToLine className="w-3.5 h-3.5" /> Download Summary CSV
          </button>
        </div>

        <div className="bg-white border border-slate-200 rounded-xl p-5 shadow-xs flex flex-col justify-between">
          <div>
            <div className="w-9 h-9 rounded-lg bg-emerald-50 text-emerald-600 flex items-center justify-center mb-3">
              <Layers className="w-5 h-5" />
            </div>
            <h3 className="text-sm font-bold text-slate-900">Clean RF Polygon Vectors</h3>
            <p className="text-xs text-slate-500 mt-1 leading-normal">
              Mutually exclusive vector GeoJSONs (Mine, Forest, Settlement, Water) with exact 7,955.83 ha boundary integrity.
            </p>
            <div className="mt-2 text-[10px] font-mono text-slate-400">
              outputs/polygons_rf_clean_2021-2026/rf_clean_polygons_*.geojson
            </div>
          </div>
          <button
            onClick={() => alert("Available in outputs/polygons_rf_clean_2021-2026/ (2021-2026 GeoJSONs)")}
            className="mt-4 w-full py-2 px-3 rounded-lg bg-teal-600 hover:bg-teal-500 text-white text-xs font-semibold flex items-center justify-center gap-2 transition-colors cursor-pointer"
          >
            <ArrowDownToLine className="w-3.5 h-3.5" /> Access GeoJSON Layer Set
          </button>
        </div>

        <div className="bg-white border border-slate-200 rounded-xl p-5 shadow-xs flex flex-col justify-between">
          <div>
            <div className="w-9 h-9 rounded-lg bg-purple-50 text-purple-600 flex items-center justify-center mb-3">
              <ShieldCheck className="w-5 h-5" />
            </div>
            <h3 className="text-sm font-bold text-slate-900">Buffer Impact Zone Metrics</h3>
            <p className="text-xs text-slate-500 mt-1 leading-normal">
              250m, 500m, and 1000m radial blast &amp; runoff environmental exposure calculations per epoch.
            </p>
            <div className="mt-2 text-[10px] font-mono text-slate-400">
              outputs/proximity_rf_clean_2021-2026/buffer_exposure/
            </div>
          </div>
          <button
            onClick={() => alert("Available in outputs/proximity_rf_clean_2021-2026/buffer_exposure/")}
            className="mt-4 w-full py-2 px-3 rounded-lg bg-slate-900 hover:bg-slate-800 text-white text-xs font-semibold flex items-center justify-center gap-2 transition-colors cursor-pointer"
          >
            <ArrowDownToLine className="w-3.5 h-3.5" /> Download Buffer Logs
          </button>
        </div>
      </div>

      {/* Complete File Catalog Table */}
      <div className="bg-white border border-slate-200 rounded-xl shadow-xs overflow-hidden">
        {/* Filters Toolbar */}
        <div className="p-4 border-b border-slate-100 flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div className="flex items-center gap-2">
            <FolderArchive className="w-4 h-4 text-teal-600" />
            <h3 className="text-sm font-bold text-slate-900">
              Existing Project Output Files ({filteredFiles.length} of {downloadableFiles.length})
            </h3>
          </div>

          <div className="flex flex-wrap items-center gap-2">
            {/* Search Bar */}
            <div className="relative">
              <Search className="w-3.5 h-3.5 absolute left-2.5 top-1/2 -translate-y-1/2 text-slate-400" />
              <input
                type="text"
                placeholder="Search file name or path..."
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                className="text-xs pl-8 pr-3 py-1.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-700 w-48 sm:w-56 focus:outline-teal-500"
              />
            </div>

            {/* Category Filter */}
            <select
              value={selectedCategory}
              onChange={(e) => setSelectedCategory(e.target.value)}
              className="text-xs bg-slate-50 border border-slate-200 rounded-lg px-2.5 py-1.5 text-slate-700 font-medium"
            >
              {categories.map((cat) => (
                <option key={cat} value={cat}>
                  {cat === "all" ? "All Modules" : cat}
                </option>
              ))}
            </select>

            {/* Format Filter */}
            <select
              value={formatFilter}
              onChange={(e) => setFormatFilter(e.target.value)}
              className="text-xs bg-slate-50 border border-slate-200 rounded-lg px-2.5 py-1.5 text-slate-700 font-medium"
            >
              {formats.map((fmt) => (
                <option key={fmt} value={fmt}>
                  {fmt === "all" ? "All Formats" : fmt}
                </option>
              ))}
            </select>
          </div>
        </div>

        {/* Catalog Table */}
        <div className="overflow-x-auto max-h-96">
          <table className="w-full text-left text-xs">
            <thead className="bg-slate-50/80 text-slate-600 sticky top-0 border-b border-slate-100 font-semibold z-10">
              <tr>
                <th className="py-2.5 px-4">File Name</th>
                <th className="py-2.5 px-4">Module</th>
                <th className="py-2.5 px-4">Relative Path</th>
                <th className="py-2.5 px-4">Format</th>
                <th className="py-2.5 px-4 text-right">Size (KB)</th>
                <th className="py-2.5 px-4 text-center">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 font-mono text-[11px] text-slate-700">
              {filteredFiles.map((file, idx) => {
                const badgeColor =
                  file.ext === "GEOJSON"
                    ? "bg-emerald-50 text-emerald-700 border-emerald-200"
                    : file.ext === "CSV"
                    ? "bg-sky-50 text-sky-700 border-sky-200"
                    : file.ext === "JSON"
                    ? "bg-amber-50 text-amber-700 border-amber-200"
                    : file.ext === "TIF"
                    ? "bg-purple-50 text-purple-700 border-purple-200"
                    : "bg-slate-100 text-slate-700 border-slate-200";

                return (
                  <tr key={idx} className="hover:bg-slate-50/80 transition-colors">
                    <td className="py-2 px-4 font-semibold text-slate-900 font-sans flex items-center gap-1.5">
                      <FileText className="w-3.5 h-3.5 text-slate-400 shrink-0" />
                      <span className="truncate max-w-xs">{file.name}</span>
                    </td>
                    <td className="py-2 px-4 font-sans text-slate-600">
                      {file.category}
                    </td>
                    <td className="py-2 px-4 text-slate-400 truncate max-w-md" title={file.path}>
                      {file.path}
                    </td>
                    <td className="py-2 px-4">
                      <span className={`px-2 py-0.5 rounded text-[10px] font-semibold border ${badgeColor}`}>
                        {file.ext}
                      </span>
                    </td>
                    <td className="py-2 px-4 text-right">
                      {file.size_kb.toFixed(1)}
                    </td>
                    <td className="py-2 px-4 text-center font-sans">
                      <button
                        onClick={() => handleDownload(file)}
                        className="p-1 rounded text-teal-600 hover:text-teal-800 hover:bg-teal-50 transition-colors cursor-pointer"
                        title="View file path"
                      >
                        <Download className="w-3.5 h-3.5 inline" />
                      </button>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </div>

      {/* Sensor & Model Technical Specifications */}
      <div className="bg-white border border-slate-200 rounded-xl p-5 shadow-xs">
        <h3 className="text-sm font-semibold text-slate-900 mb-3 flex items-center gap-2">
          <CheckCircle className="w-4 h-4 text-emerald-600" /> Scientific Methodology &amp; Sensor Specifications
        </h3>
        <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-4 gap-4 text-xs text-slate-600 pt-2 border-t border-slate-100">
          <div>
            <span className="text-slate-400 block text-[11px]">Primary Satellite:</span>
            <span className="font-semibold text-slate-900">{SATELLITE_SPECIFICATIONS.sensor}</span>
          </div>
          <div>
            <span className="text-slate-400 block text-[11px]">Ground Reference:</span>
            <span className="font-semibold text-slate-900">ESA WorldCover v200 (10m)</span>
          </div>
          <div>
            <span className="text-slate-400 block text-[11px]">RF Classifier Accuracy:</span>
            <span className="font-semibold text-emerald-600">{SATELLITE_SPECIFICATIONS.rfValidationAccuracy}</span>
          </div>
          <div>
            <span className="text-slate-400 block text-[11px]">Kappa Coefficient:</span>
            <span className="font-semibold text-teal-600">{SATELLITE_SPECIFICATIONS.rfKappa}</span>
          </div>
        </div>
      </div>
    </div>
  );
}